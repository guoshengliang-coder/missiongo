#!/usr/bin/env node
// Product identity is declared in product.json. Generated copies are checked,
// never independently edited. Raster receipts avoid font/platform differences
// in social cards making a clean checkout appear dirty on another OS.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = (path) => readFileSync(resolve(root, path));
const hash = (value) => createHash("sha256").update(value).digest("hex");
const xml = (value) => value.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;");
const attrs = (source) => Object.fromEntries([...source.matchAll(/([\w-]+)="([^"]*)"/g)].map((match) => [match[1], match[2]]));

// Deliberately narrow SVG vocabulary: unsupported artwork must fail generation
// rather than silently disappear from one platform's icon.
export function androidVector(svg, { adaptive = false } = {}) {
  const nodes = svg.replace(/<!--[\s\S]*?-->/g, "").match(/<[^>]+>/g) ?? [];
  const stack = [{}];
  const output = [];
  for (const node of nodes) {
    if (/^<\/?svg\b/.test(node)) continue;
    if (node === "</g>") { stack.pop(); output.push("    </group>"); continue; }
    const values = { ...stack.at(-1), ...attrs(node) };
    if (/^<g\b/.test(node)) {
      const transform = /^translate\(([\d.]+) ([\d.]+)\) scale\(([\d.]+)\)$/.exec(values.transform);
      if (!transform) throw new Error("Unsupported brand SVG group transform");
      const [, x, y, scale] = transform;
      output.push(`    <group android:translateX="${x}" android:translateY="${y}" android:scaleX="${scale}" android:scaleY="${scale}">`);
      stack.push(values);
    } else if (/^<path\b/.test(node)) {
      const fields = { pathData: values.d, fillColor: values.fill === "none" ? "#00000000" : values.fill };
      for (const [from, to] of Object.entries({ stroke: "strokeColor", "stroke-width": "strokeWidth", "stroke-linecap": "strokeLineCap", "stroke-linejoin": "strokeLineJoin" })) {
        if (values[from]) fields[to] = values[from];
      }
      output.push(`    <path ${Object.entries(fields).map(([key, value]) => `android:${key}="${xml(value)}"`).join(" ")} />`);
    } else throw new Error(`Unsupported brand SVG node: ${node}`);
  }
  const viewport = adaptive ? 108 : 40;
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/product-branding.mjs; edit product.json / its iconSource. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">\n${output.join("\n")}\n</vector>\n`;
}

export function brandAssets() {
  const product = JSON.parse(read("product.json"));
  const source = read(product.iconSource).toString();
  if (!source.includes('viewBox="0 0 40 40"')) throw new Error("Brand icon must use the 40-unit header canvas");
  const rocket = /<g id="rocket"[\s\S]*?<\/g>/.exec(source)?.[0];
  if (!rocket) throw new Error("Brand icon must contain the shared rocket group");
  const background = /<path fill="(#[0-9A-F]{6})" stroke=/.exec(source)?.[1];
  if (!background) throw new Error("Brand icon must declare its tile colour");
  const stroke = attrs(rocket).stroke;
  // The glyph fits inside the central safe circle (66/108), even when Android
  // masks a launcher into a circle, squircle or rounded square.
  const adaptive = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">${rocket.replace(/transform="[^"]*"/, 'transform="translate(27.6 27.6) scale(2.2)"')}</svg>`;
  const maskable = adaptive.replace(/(<svg[^>]*>)/, `$1<path fill="${background}" d="M0 0H108V108H0Z" />`);
  const iconUrl = `/${product.icon.split("/").at(-1)}?v=${hash(source).slice(0, 12)}`;
  const description = (locale) => `${product.name} — ${product.taglines[locale]}`;
  const texts = new Map([
    [product.icon, source],
    ["apps/web/public/icon-maskable.svg", maskable + "\n"],
    [`${product.android.app.path}/src/main/res/mipmap-anydpi/ic_launcher.xml`, androidVector(source)],
    [`${product.android.app.path}/src/main/res/drawable/ic_launcher_foreground.xml`, androidVector(adaptive, { adaptive: true })],
    ["apps/web/src/branding.generated.ts", `// Generated by scripts/product-branding.mjs from product.json.\nexport const PRODUCT_NAME = ${JSON.stringify(product.name)};\nexport const PRODUCT_ICON_URL = ${JSON.stringify(iconUrl)};\nexport const PRODUCT_TAGLINES = ${JSON.stringify(product.taglines, null, 2)} as const;\n`],
  ]);
  const colorsPath = `${product.android.app.path}/src/main/res/values/colors.xml`;
  texts.set(colorsPath, read(colorsPath).toString().replace(/(<color name="missiongo_icon_background">)[^<]+/, `$1${background}`));

  const raster = new Map();
  for (const size of [32, 180, 192, 512, 1024]) raster.set(`apps/web/public/icon-${size}.png`, { svg: source, width: size, height: size });
  for (const size of [192, 512]) raster.set(`apps/web/public/icon-maskable-${size}.png`, { svg: maskable, width: size, height: size });
  for (const locale of ["zh-CN", "en"]) {
    const manifest = {
      id: "/", name: product.name, short_name: product.name, description: product.taglines[locale], lang: locale,
      start_url: "/", scope: "/", display: "standalone", background_color: background, theme_color: stroke,
      icons: [
        { src: iconUrl, sizes: "any", type: "image/svg+xml", purpose: "any" },
        ...[192, 512].flatMap((size) => [
          { src: `/icon-${size}.png?v=${hash(source).slice(0, 12)}`, sizes: `${size}x${size}`, type: "image/png", purpose: "any" },
          { src: `/icon-maskable-${size}.png?v=${hash(maskable).slice(0, 12)}`, sizes: `${size}x${size}`, type: "image/png", purpose: "maskable" },
        ]),
      ],
    };
    texts.set(`apps/web/public/manifest${locale === "en" ? "-en" : ""}.webmanifest`, JSON.stringify(manifest, null, 2) + "\n");
    // Rebuild the card from vector artwork; do not leave the old slogan baked
    // into an otherwise updated social preview. Both locales have real PNGs.
    const social = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630"><rect width="1200" height="630" fill="${stroke}"/><g transform="translate(72 76) scale(3.5)">${source.replace(/<\/?svg[^>]*>/g, "")}</g><text x="246" y="176" fill="${background}" font-family="Arial, sans-serif" font-weight="700" font-size="80">${xml(product.name)}</text><text x="76" y="326" fill="#FBFAF7" font-family="Arial, PingFang SC, sans-serif" font-size="48">${xml(product.taglines[locale])}</text><path d="M80 440H1110" stroke="${background}" stroke-width="4"/><g fill="${background}"><circle cx="80" cy="440" r="12"/><circle cx="420" cy="440" r="12"/><circle cx="760" cy="440" r="12"/><circle cx="1110" cy="440" r="12"/></g></svg>\n`;
    const socialName = locale === "en" ? "og-en" : "og";
    texts.set(`assets/brand/${socialName}.svg`, social);
    raster.set(`apps/web/public/${socialName}.png`, { svg: social, width: 1200, height: 630 });
  }

  // Keep the HTML legible without a Vite-only template. --check compares these
  // substitutions too; copies can never quietly diverge from product.json.
  const htmlPath = "apps/web/index.html";
  let html = read(htmlPath).toString()
    .replace(/<title>[^<]*<\/title>/, `<title>${xml(product.name)} · ${xml(product.taglines["zh-CN"])}</title>`)
    .replace(/<link rel="icon"[^>]*\/>/, `<link rel="icon" href="${iconUrl}" type="image/svg+xml" />`)
    .replace(/<link rel="apple-touch-icon"[^>]*\/>/, `<link rel="apple-touch-icon" href="/icon-180.png?v=${hash(source).slice(0, 12)}" />`);
  for (const attribute of ['name="description"', 'property="og:description"', 'name="twitter:description"']) {
    html = html.replace(new RegExp(`(<meta ${attribute} content=")[^"]*`), `$1${xml(description("zh-CN"))}`);
  }
  texts.set(htmlPath, html);
  for (const [path, quote] of [["README.md", "> "], ["docs/product-and-technical-plan.md", "> **"]]) {
    texts.set(path, read(path).toString().replace(/^> .*$/m, `${quote}${product.taglines["zh-CN"]}${quote.endsWith("**") ? "**" : ""}`));
  }
  // Unrelated HTML/document edits do not invalidate raster receipts.
  return { texts, raster, sourceDigest: hash(JSON.stringify([...raster])), product };
}

export async function syncBrandAssets({ check = false } = {}) {
  const { texts, raster, sourceDigest } = brandAssets();
  const failures = [];
  const put = (path, data) => { mkdirSync(dirname(resolve(root, path)), { recursive: true }); writeFileSync(resolve(root, path), data); };
  for (const [path, expected] of texts) {
    if (!check) put(path, expected);
    else { try { if (read(path).toString() !== expected) failures.push(path); } catch { failures.push(path); } }
  }
  const receiptPath = "assets/brand/generated.json";
  if (check) {
    let receipt;
    try { receipt = JSON.parse(read(receiptPath)); } catch { failures.push(receiptPath); }
    if (receipt?.sourceDigest !== sourceDigest) failures.push("branding source digest");
    for (const [path, { width, height }] of raster) {
      try {
        const bytes = read(path);
        const meta = await sharp(bytes).metadata();
        if (hash(bytes) !== receipt?.rasters[path] || meta.width !== width || meta.height !== height) failures.push(path);
      } catch { failures.push(path); }
    }
  } else {
    const rasters = {};
    for (const [path, { svg, width, height }] of raster) {
      const bytes = await sharp(Buffer.from(svg)).resize(width, height).png().toBuffer();
      put(path, bytes);
      rasters[path] = hash(bytes);
    }
    put(receiptPath, JSON.stringify({ sourceDigest, rasters }, null, 2) + "\n");
  }
  if (failures.length) throw new Error(`Brand assets differ from product.json / iconSource: ${failures.join(", ")}. Run npm run generate:branding.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await syncBrandAssets({ check: process.argv.includes("--check") });
  console.log(process.argv.includes("--check") ? "Product branding is consistent." : "Product branding generated.");
}
